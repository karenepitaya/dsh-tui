function assistant(
  key: string,
  text: string,
  reasoning = '',
): ConversationNode {
  return {
    kind: 'assistant',
    key,
    revision: `${text.length}:${reasoning.length}`,
    text,
    reasoning,
    ...(reasoning === '' ? {} : { reasoningSummary: 'THINKING · 1 lines' }),
  }
}

function surface(
  sessionId: string,
  bindingEpoch: number,
  nodes: readonly ConversationNode[],
  reasoningExpanded = false,
): ConversationSurface {
  return {
    sessionId,
    bindingEpoch,
    header: `DSH-TUI · ${sessionId}`,
    nodes,
    composer: '',
    composerColumn: 0,
    composerPrefix: '> ',
    footer: 'Ctrl+F search',
    reasoningExpanded,
  }
}

