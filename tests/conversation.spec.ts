describe('markdown source safety', () => {
  it('downgrades relative, custom, and overlong destinations to visible text', () => {
    const long = 'https://example.com/' + 'x'.repeat(2050)
    const output = sanitizeMarkdownSource(
      `[relative](./a) [custom](dsh:run) [long](${long})`,
    )
    expect(output).toContain('relative (./a)')
    expect(output).toContain('custom (dsh:run)')
    expect(output).toContain('long (https://example.com/')
  })

  it('filters unsafe definitions, images, and autolinks while retaining safe URLs', () => {
    const output = sanitizeMarkdownSource([
      '[safe]: <https://example.com/path> "title"',
      '[bad]: javascript:alert(1)',
      '![bad image](file:///C:/secret)',
      '![](file:///C:/secret)',
      '[empty]()',
      '<javascript:alert(1)>',
      '<mailto:test@example.com>',
      '\x1bPowned\x1b\\tab\tcontrol\u0001',
    ].join('\r\n'))

    expect(output).toContain('[safe]: <https://example.com/path> "title"')
    expect(output).not.toContain('[bad]:')
    expect(output).toContain('[image: bad image]')
    expect(output).toContain('[image: attachment]')
    expect(output).toContain('empty')
    expect(output).toContain('javascript:alert(1)')
    expect(output).toContain('<mailto:test@example.com>')
    expect(output).toContain('tab  control�')
    expect(output).not.toContain('\x1b')
  })

  it('retains a visible URL when terminal hyperlinks are unavailable', () => {
    setCapabilities({ images: null, trueColor: false, hyperlinks: false })
    const document = new ConversationDocumentComponent(mono)
    document.setNodes([{
      kind: 'assistant',
      key: 'assistant:link',
      revision: '1',
      text: '[documentation](https://example.com/docs)',
    }], false)
    expect(stripTerminalSequences(document.render(80).join('\n')))
      .toContain('https://example.com/docs')
  })

  it('removes an unsafe OSC 8 target injected by a presentation formatter', () => {
    setCapabilities({ images: null, trueColor: false, hyperlinks: false })
    const hostileTheme = {
      ...mono,
      paint: (role: Parameters<typeof mono.paint>[0], value: string): string => (
        role === 'muted'
          ? `\x1b]8;;javascript:owned\x1b\\${value}\x1b]8;;\x1b\\`
          : value
      ),
    }
    const document = new ConversationDocumentComponent(hostileTheme)
    document.setNodes([{
      kind: 'assistant',
      key: 'assistant:formatter-link',
      revision: '1',
      text: '[documentation](https://example.com/docs)',
    }], false)
    const output = document.render(10).join('\n')
    expect(output).not.toContain('javascript:owned')
    expect(stripTerminalSequences(output)).toContain('documentat')
  })
})
